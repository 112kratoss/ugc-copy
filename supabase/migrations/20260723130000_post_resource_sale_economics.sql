CREATE TRIGGER post_resource_order_creator_refund
AFTER UPDATE OF status ON public.post_resource_bundle_orders
FOR EACH ROW
EXECUTE FUNCTION public.reverse_post_resource_wallet_on_refund();

-- Existing purchase functions update the legacy earnings column with gross
-- price after inserting/deleting an entitlement. Keep those callers backward
-- compatible while ensuring the legacy projection always reflects net creator
-- proceeds from the exact ledger.
CREATE OR REPLACE FUNCTION public.normalize_post_resource_legacy_earnings()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
  NEW.earnings_usd_cents := floor(
    NEW.creator_earnings_token_subunits::numeric / 100
  )::integer;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS post_resource_bundle_normalize_legacy_earnings
  ON public.post_resource_bundles;
CREATE TRIGGER post_resource_bundle_normalize_legacy_earnings
BEFORE UPDATE OF earnings_usd_cents, creator_earnings_token_subunits
ON public.post_resource_bundles
FOR EACH ROW
EXECUTE FUNCTION public.normalize_post_resource_legacy_earnings();

