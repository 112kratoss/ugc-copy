-- Backfill each retained purchase. The purchase price is the authoritative
-- token amount; payment-provider subunits may instead be INR or another cash
-- currency and must not be used for the creator split.
INSERT INTO public.creator_resource_wallet_entries (
  event_key,
  user_id,
  bundle_id,
  purchase_id,
  order_id,
  entry_kind,
  gross_token_units,
  creator_amount_token_subunits,
  platform_fee_token_subunits,
  created_at
)
SELECT
  'purchase:' || purchases.id::text,
  bundles.owner_user_id,
  bundles.id,
  purchases.id,
  purchases.order_id,
  'sale',
  purchases.price_usd_cents,
  purchases.price_usd_cents::bigint * 85,
  purchases.price_usd_cents::bigint * 15,
  purchases.created_at
FROM public.post_resource_bundle_purchases AS purchases
JOIN public.post_resource_bundles AS bundles ON bundles.id = purchases.bundle_id
WHERE purchases.price_usd_cents > 0
ON CONFLICT (event_key) DO NOTHING;

-- Preserve pre-ledger aggregate sales that no longer have individual retained
-- purchase rows (for example, legacy imports). This credits only the positive
-- gap and never double-counts purchases backfilled above.
WITH retained_sales AS (
  SELECT
    bundles.id AS bundle_id,
    bundles.owner_user_id,
    bundles.created_at,
    greatest(
      0,
      bundles.earnings_usd_cents
        - coalesce(sum(purchases.price_usd_cents), 0)
    )::integer AS legacy_gross_tokens
  FROM public.post_resource_bundles AS bundles
  LEFT JOIN public.post_resource_bundle_purchases AS purchases
    ON purchases.bundle_id = bundles.id
  GROUP BY bundles.id, bundles.owner_user_id, bundles.created_at, bundles.earnings_usd_cents
)
INSERT INTO public.creator_resource_wallet_entries (
  event_key,
  user_id,
  bundle_id,
  purchase_id,
  order_id,
  entry_kind,
  gross_token_units,
  creator_amount_token_subunits,
  platform_fee_token_subunits,
  created_at
)
SELECT
  'legacy-bundle:' || bundle_id::text,
  owner_user_id,
  bundle_id,
  NULL,
  NULL,
  'legacy_sale',
  legacy_gross_tokens,
  legacy_gross_tokens::bigint * 85,
  legacy_gross_tokens::bigint * 15,
  created_at
FROM retained_sales
WHERE legacy_gross_tokens > 0
ON CONFLICT (event_key) DO NOTHING;

INSERT INTO public.creator_resource_wallets (
  user_id,
  available_token_subunits,
  lifetime_earned_token_subunits,
  lifetime_refunded_token_subunits,
  updated_at
)
SELECT
  entries.user_id,
  sum(entries.creator_amount_token_subunits),
  sum(greatest(entries.creator_amount_token_subunits, 0)),
  sum(greatest(-entries.creator_amount_token_subunits, 0)),
  timezone('utc'::text, now())
FROM public.creator_resource_wallet_entries AS entries
GROUP BY entries.user_id
ON CONFLICT (user_id) DO UPDATE
SET available_token_subunits = EXCLUDED.available_token_subunits,
    lifetime_earned_token_subunits = EXCLUDED.lifetime_earned_token_subunits,
    lifetime_refunded_token_subunits = EXCLUDED.lifetime_refunded_token_subunits,
    updated_at = EXCLUDED.updated_at;

WITH bundle_totals AS (
  SELECT
    bundles.id AS bundle_id,
    coalesce(sum(entries.gross_token_units), 0)::bigint AS gross_tokens,
    coalesce(sum(entries.creator_amount_token_subunits), 0)::bigint AS creator_subunits,
    coalesce(sum(entries.platform_fee_token_subunits), 0)::bigint AS platform_subunits
  FROM public.post_resource_bundles AS bundles
  LEFT JOIN public.creator_resource_wallet_entries AS entries
    ON entries.bundle_id = bundles.id
  GROUP BY bundles.id
)
UPDATE public.post_resource_bundles AS bundles
SET gross_sales_tokens = totals.gross_tokens,
    creator_earnings_token_subunits = totals.creator_subunits,
    platform_fee_token_subunits = totals.platform_subunits,
    earnings_usd_cents = floor(totals.creator_subunits::numeric / 100)::integer
FROM bundle_totals AS totals
WHERE totals.bundle_id = bundles.id;

CREATE OR REPLACE FUNCTION public.apply_post_resource_wallet_purchase_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_owner_user_id uuid;
  v_entry_id bigint;
  v_creator_subunits bigint;
  v_platform_subunits bigint;
BEGIN
  IF NEW.price_usd_cents <= 0 THEN
    RETURN NEW;
  END IF;

  SELECT owner_user_id
  INTO v_owner_user_id
  FROM public.post_resource_bundles
  WHERE id = NEW.bundle_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Resource bundle not found for creator settlement';
  END IF;

  v_creator_subunits := NEW.price_usd_cents::bigint * 85;
  v_platform_subunits := NEW.price_usd_cents::bigint * 15;

  INSERT INTO public.creator_resource_wallet_entries (
    event_key,
    user_id,
    bundle_id,
    purchase_id,
    order_id,
    entry_kind,
    gross_token_units,
    creator_amount_token_subunits,
    platform_fee_token_subunits
  ) VALUES (
    'purchase:' || NEW.id::text,
    v_owner_user_id,
    NEW.bundle_id,
    NEW.id,
    NEW.order_id,
    'sale',
    NEW.price_usd_cents,
    v_creator_subunits,
    v_platform_subunits
  )
  ON CONFLICT (event_key) DO NOTHING
  RETURNING id INTO v_entry_id;

  IF v_entry_id IS NOT NULL THEN
    INSERT INTO public.creator_resource_wallets (
      user_id,
      available_token_subunits,
      lifetime_earned_token_subunits
    ) VALUES (
      v_owner_user_id,
      v_creator_subunits,
      v_creator_subunits
    )
    ON CONFLICT (user_id) DO UPDATE
    SET available_token_subunits = creator_resource_wallets.available_token_subunits
          + EXCLUDED.available_token_subunits,
        lifetime_earned_token_subunits = creator_resource_wallets.lifetime_earned_token_subunits
          + EXCLUDED.lifetime_earned_token_subunits,
        updated_at = timezone('utc'::text, now());

    UPDATE public.post_resource_bundles
    SET gross_sales_tokens = gross_sales_tokens + NEW.price_usd_cents,
        creator_earnings_token_subunits = creator_earnings_token_subunits + v_creator_subunits,
        platform_fee_token_subunits = platform_fee_token_subunits + v_platform_subunits,
        updated_at = timezone('utc'::text, now())
    WHERE id = NEW.bundle_id;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS post_resource_purchase_creator_settlement
  ON public.post_resource_bundle_purchases;
CREATE TRIGGER post_resource_purchase_creator_settlement
AFTER INSERT ON public.post_resource_bundle_purchases
FOR EACH ROW
EXECUTE FUNCTION public.apply_post_resource_wallet_purchase_change();

CREATE OR REPLACE FUNCTION public.reverse_post_resource_wallet_on_refund()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_sale public.creator_resource_wallet_entries%ROWTYPE;
  v_entry_id bigint;
BEGIN
  IF OLD.status <> 'paid' OR NEW.status <> 'failed' THEN
    RETURN NEW;
  END IF;

  -- Account or post deletion removes orders rather than transitioning them.
  -- A paid-to-failed transition only reverses settlement after the entitlement
  -- row has actually been removed by the authoritative refund transaction.
  IF EXISTS (
    SELECT 1
    FROM public.post_resource_bundle_purchases
    WHERE order_id = NEW.id
  ) THEN
    RETURN NEW;
  END IF;

  SELECT entries.*
  INTO v_sale
  FROM public.creator_resource_wallet_entries AS entries
  WHERE entries.order_id = NEW.id
    AND entries.entry_kind = 'sale'
    AND NOT EXISTS (
      SELECT 1
      FROM public.creator_resource_wallet_entries AS refunds
      WHERE refunds.event_key = 'refund-purchase:' || entries.purchase_id::text
    )
  ORDER BY entries.id DESC
  LIMIT 1;

  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.creator_resource_wallet_entries (
    event_key,
    user_id,
    bundle_id,
    purchase_id,
    order_id,
    entry_kind,
    gross_token_units,
    creator_amount_token_subunits,
    platform_fee_token_subunits
  ) VALUES (
    'refund-purchase:' || v_sale.purchase_id::text,
    v_sale.user_id,
    v_sale.bundle_id,
    v_sale.purchase_id,
    NEW.id,
    'refund',
    v_sale.gross_token_units,
    -v_sale.creator_amount_token_subunits,
    -v_sale.platform_fee_token_subunits
  )
  ON CONFLICT (event_key) DO NOTHING
  RETURNING id INTO v_entry_id;

  IF v_entry_id IS NOT NULL THEN
    UPDATE public.creator_resource_wallets
    SET available_token_subunits = available_token_subunits
          - v_sale.creator_amount_token_subunits,
        lifetime_refunded_token_subunits = lifetime_refunded_token_subunits
          + v_sale.creator_amount_token_subunits,
        updated_at = timezone('utc'::text, now())
    WHERE user_id = v_sale.user_id;

    UPDATE public.post_resource_bundles
    SET gross_sales_tokens = greatest(
          0,
          gross_sales_tokens - v_sale.gross_token_units
        ),
        creator_earnings_token_subunits = greatest(
          0,
          creator_earnings_token_subunits - v_sale.creator_amount_token_subunits
        ),
        platform_fee_token_subunits = greatest(
          0,
          platform_fee_token_subunits - v_sale.platform_fee_token_subunits
        ),
        updated_at = timezone('utc'::text, now())
    WHERE id = v_sale.bundle_id;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS post_resource_order_creator_refund
