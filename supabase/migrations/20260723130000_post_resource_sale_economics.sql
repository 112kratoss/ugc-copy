-- Resource package economics use whole tokens for pricing (100 tokens = USD 1)
-- and hundredths of a token for settlement. The finer settlement unit keeps an
-- exact 85/15 split even for the 10-token minimum price.

ALTER TABLE public.post_resource_bundles
  ADD COLUMN IF NOT EXISTS gross_sales_tokens bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS creator_earnings_token_subunits bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS platform_fee_token_subunits bigint NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.post_resource_bundles.price_usd_cents IS
  'Resource package price in whole tokens. At the fixed 100-token/USD rate, one token is also one USD cent.';
COMMENT ON COLUMN public.post_resource_bundles.earnings_usd_cents IS
  'Legacy creator earnings projection in whole USD cents, rounded down from exact token subunits.';
COMMENT ON COLUMN public.post_resource_bundles.creator_earnings_token_subunits IS
  'Exact creator proceeds where 100 subunits equal one token; creator share is 85 percent.';
COMMENT ON COLUMN public.post_resource_bundles.platform_fee_token_subunits IS
  'Exact platform proceeds where 100 subunits equal one token; platform share is 15 percent.';

-- Native clients unlock post packages with their credit balance. Keep existing
-- pending store intents settleable for backward compatibility, but reject all
-- newly-created direct-IAP intents for this entitlement type.
UPDATE public.mobile_store_products
SET active = false,
    updated_at = timezone('utc'::text, now())
WHERE entitlement_type = 'post_resource_unlock'
  AND active = true;

