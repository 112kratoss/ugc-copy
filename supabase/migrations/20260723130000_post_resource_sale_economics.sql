CREATE TABLE IF NOT EXISTS public.creator_resource_wallets (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  available_token_subunits bigint NOT NULL DEFAULT 0,
  lifetime_earned_token_subunits bigint NOT NULL DEFAULT 0 CHECK (lifetime_earned_token_subunits >= 0),
  lifetime_refunded_token_subunits bigint NOT NULL DEFAULT 0 CHECK (lifetime_refunded_token_subunits >= 0),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.creator_resource_wallet_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key text UNIQUE NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  bundle_id uuid REFERENCES public.post_resource_bundles(id) ON DELETE SET NULL,
  purchase_id uuid,
  order_id uuid,
  entry_kind text NOT NULL CHECK (entry_kind IN ('sale', 'refund', 'legacy_sale')),
  gross_token_units integer NOT NULL CHECK (gross_token_units >= 0),
  creator_amount_token_subunits bigint NOT NULL,
  platform_fee_token_subunits bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT creator_resource_wallet_entry_split_check CHECK (
    creator_amount_token_subunits + platform_fee_token_subunits
      = CASE
          WHEN entry_kind = 'refund' THEN -(gross_token_units::bigint * 100)
          ELSE gross_token_units::bigint * 100
        END
  )
);

CREATE INDEX IF NOT EXISTS creator_resource_wallet_entries_user_created_idx
  ON public.creator_resource_wallet_entries (user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS creator_resource_wallet_entries_bundle_idx
  ON public.creator_resource_wallet_entries (bundle_id, id DESC);
CREATE INDEX IF NOT EXISTS creator_resource_wallet_entries_purchase_idx
  ON public.creator_resource_wallet_entries (purchase_id)
  WHERE purchase_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS creator_resource_wallet_entries_order_idx
  ON public.creator_resource_wallet_entries (order_id, id DESC)
  WHERE order_id IS NOT NULL;

ALTER TABLE public.creator_resource_wallets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.creator_resource_wallet_entries ENABLE ROW LEVEL SECURITY;

