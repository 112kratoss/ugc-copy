  bundle_orders.id,
  purchases.id,
  purchases.price_usd_cents,
  purchases.amount_subunits,
  purchases.currency,
  purchases.created_at
FROM public.marketplace_purchases purchases
JOIN public.post_resource_bundles bundles
  ON bundles.legacy_asset_id = purchases.asset_id
JOIN public.post_resource_bundle_orders bundle_orders
  ON bundle_orders.legacy_order_id = purchases.order_id
ON CONFLICT (legacy_purchase_id) DO NOTHING;

