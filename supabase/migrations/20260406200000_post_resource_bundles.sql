CREATE OR REPLACE FUNCTION public.complete_post_resource_bundle_purchase(
  p_razorpay_order_id text,
  p_razorpay_payment_id text
)
RETURNS boolean AS $$
DECLARE
  v_order public.post_resource_bundle_orders%ROWTYPE;
  v_bundle public.post_resource_bundles%ROWTYPE;
  v_purchase_id uuid;
BEGIN
  SELECT *
  INTO v_order
  FROM public.post_resource_bundle_orders
  WHERE razorpay_order_id = p_razorpay_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  IF v_order.status = 'paid' THEN
    RETURN false;
  END IF;

  SELECT *
  INTO v_bundle
  FROM public.post_resource_bundles
  WHERE id = v_order.bundle_id;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE public.post_resource_bundle_orders
  SET status = 'paid',
      razorpay_payment_id = p_razorpay_payment_id,
      updated_at = timezone('utc'::text, now())
  WHERE id = v_order.id;

  INSERT INTO public.post_resource_bundle_purchases (
    bundle_id,
    buyer_user_id,
    order_id,
    price_usd_cents,
    amount_subunits,
    currency
  )
  VALUES (
    v_order.bundle_id,
    v_order.buyer_user_id,
    v_order.id,
    v_bundle.price_usd_cents,
    v_order.amount_subunits,
    v_order.currency
  )
  ON CONFLICT (bundle_id, buyer_user_id) DO NOTHING
  RETURNING id INTO v_purchase_id;

  IF v_purchase_id IS NULL THEN
    RETURN false;
  END IF;

  UPDATE public.post_resource_bundles
  SET sales_count = sales_count + 1,
      earnings_usd_cents = earnings_usd_cents + v_bundle.price_usd_cents,
      updated_at = timezone('utc'::text, now())
  WHERE id = v_order.bundle_id;

  RETURN true;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION public.complete_post_resource_bundle_purchase(text, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.complete_post_resource_bundle_purchase(text, text) FROM anon;
REVOKE ALL ON FUNCTION public.complete_post_resource_bundle_purchase(text, text) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.complete_post_resource_bundle_purchase(text, text) TO service_role;

INSERT INTO public.post_resource_bundles (
  post_id,
  owner_user_id,
  legacy_asset_id,
  access_mode,
  status,
  title,
  summary,
  preview_text,
  prompt_text,
  notes_markdown,
  workflow_snapshot,
  attachments,
  allow_remix,
  price_usd_cents,
  sales_count,
  earnings_usd_cents,
  created_at,
  updated_at
)
SELECT
  assets.post_id,
  assets.seller_user_id,
  assets.id,
  CASE
    WHEN assets.price_usd_cents = 0 THEN 'free'
    ELSE 'paid'
  END,
  CASE
    WHEN assets.status = 'active' AND posts.visibility = 'public' THEN 'published'
    ELSE 'draft'
  END,
  COALESCE(NULLIF(assets.title, ''), COALESCE(posts.title, 'Attached resources')),
  assets.description,
  assets.preview,
  content.prompt_pack,
  content.guide_markdown,
  content.workflow_graph,
  '[]'::jsonb,
  false,
  assets.price_usd_cents,
  assets.sales_count,
  assets.earnings_usd_cents,
  assets.created_at,
  assets.updated_at
FROM public.marketplace_assets assets
JOIN public.posts
  ON posts.id = assets.post_id
LEFT JOIN public.marketplace_asset_content content
  ON content.asset_id = assets.id
WHERE assets.post_id IS NOT NULL
  AND assets.status <> 'deleted'
ON CONFLICT (post_id) DO UPDATE
SET
  legacy_asset_id = EXCLUDED.legacy_asset_id,
  access_mode = EXCLUDED.access_mode,
  status = EXCLUDED.status,
  title = EXCLUDED.title,
  summary = EXCLUDED.summary,
  preview_text = EXCLUDED.preview_text,
  prompt_text = EXCLUDED.prompt_text,
  notes_markdown = EXCLUDED.notes_markdown,
  workflow_snapshot = EXCLUDED.workflow_snapshot,
  price_usd_cents = EXCLUDED.price_usd_cents,
  sales_count = EXCLUDED.sales_count,
  earnings_usd_cents = EXCLUDED.earnings_usd_cents,
  updated_at = timezone('utc'::text, now());

