CREATE TABLE IF NOT EXISTS public.post_resource_bundles (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  post_id uuid UNIQUE NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
  owner_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  legacy_asset_id uuid UNIQUE REFERENCES public.marketplace_assets(id) ON DELETE SET NULL,
  access_mode text NOT NULL CHECK (access_mode IN ('free', 'paid')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  title text NOT NULL,
  summary text NOT NULL DEFAULT '',
  preview_text text NOT NULL DEFAULT '',
  prompt_text text,
  notes_markdown text,
  workflow_share_url text,
  workflow_snapshot jsonb,
  attachments jsonb NOT NULL DEFAULT '[]'::jsonb,
  allow_remix boolean NOT NULL DEFAULT false,
  price_usd_cents integer NOT NULL DEFAULT 0 CHECK (price_usd_cents = 0 OR price_usd_cents >= 100),
  sales_count integer NOT NULL DEFAULT 0,
  earnings_usd_cents integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT post_resource_bundles_access_mode_price_check CHECK (
    (access_mode = 'free' AND price_usd_cents = 0)
    OR (access_mode = 'paid' AND price_usd_cents >= 100)
  ),
  CONSTRAINT post_resource_bundles_attachments_array_check CHECK (jsonb_typeof(attachments) = 'array')
);

CREATE TABLE IF NOT EXISTS public.post_resource_bundle_orders (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  bundle_id uuid NOT NULL REFERENCES public.post_resource_bundles(id) ON DELETE CASCADE,
  buyer_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  legacy_order_id uuid UNIQUE REFERENCES public.marketplace_orders(id) ON DELETE SET NULL,
  razorpay_order_id text UNIQUE NOT NULL,
  razorpay_payment_id text,
  amount_subunits integer NOT NULL,
  currency text NOT NULL CHECK (currency IN ('INR', 'USD')),
  status text NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'paid', 'failed')),
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.post_resource_bundle_purchases (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  bundle_id uuid NOT NULL REFERENCES public.post_resource_bundles(id) ON DELETE CASCADE,
  buyer_user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  order_id uuid NOT NULL REFERENCES public.post_resource_bundle_orders(id) ON DELETE CASCADE,
  legacy_purchase_id uuid UNIQUE REFERENCES public.marketplace_purchases(id) ON DELETE SET NULL,
  price_usd_cents integer NOT NULL,
  amount_subunits integer NOT NULL,
  currency text NOT NULL CHECK (currency IN ('INR', 'USD')),
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE (bundle_id, buyer_user_id)
);

CREATE TABLE IF NOT EXISTS public.post_resource_bundle_migration_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_asset_id uuid,
  post_id uuid,
  outcome text NOT NULL CHECK (outcome IN ('migrated', 'skipped_no_post', 'skipped_not_public', 'skipped_invalid')),
  note text,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

