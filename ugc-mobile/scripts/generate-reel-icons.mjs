import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

// Run with SHARP_MODULE pointing to an installed sharp package when this mobile
// workspace has no sharp dependency. No native mobile dependency is added.
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_MODULE || 'sharp');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'assets/reel-icons');
await fs.mkdir(output, { recursive: true });
const variants = [
  ['heart', 'Heart', 30, '#ffffff', 'none', true],
  ['heart', 'Heart', 30, '#ff3b64', '#ff3b64', true],
  ['heart', 'Heart', 30, 'rgba(255,255,255,0.5)', 'none', true],
  ['message-circle', 'MessageCircle', 30, '#ffffff', 'none', false],
  ['share', 'Share', 28, '#ffffff', 'none', true],
  ['share-2', 'Share2', 28, '#ffffff', 'none', true],
  ['ellipsis', 'Ellipsis', 28, '#ffffff', 'none', true],
  ['file-text', 'FileText', 26, '#ffffff', 'none', false],
  ['repeat-2', 'Repeat2', 26, '#050505', 'none', false],
  ['globe', 'Globe', 26, '#050505', 'none', false],
  ['globe', 'Globe', 26, '#ffffff', 'none', false],
  ['wand-sparkles', 'WandSparkles', 26, '#67d6a7', 'none', false],
  ['lock-keyhole', 'LockKeyhole', 26, '#f2b95e', 'none', false],
];
const lines = [];
for (const [file, name, size, color, fill, shadow] of variants) {
  const source = await fs.readFile(path.join(root, `node_modules/lucide-react-native/dist/esm/icons/${file}.mjs`), 'utf8');
  let nodes;
  vm.runInNewContext(source.replace(/^import .*$/mg, '').replace(/^export .*$/mg, ''), {
    createLucideIcon: (_, value) => { nodes = value; },
  });
  const shape = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([key]) => key !== 'key').map(([key, value]) => `${key}="${value}"`).join(' ')} />`).join('');
  // Padding carries the original 1.5 pt shadow offset without clipping it.
  const pad = 3;
  const side = size + pad * 2;
  const group = (stroke, paint, weight, dy) => `<g transform="translate(${pad},${pad + dy}) scale(${size / 24})" stroke="${stroke}" fill="${paint}" stroke-width="${weight}" stroke-linecap="round" stroke-linejoin="round">${shape}</g>`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${side}" height="${side}">${shadow ? group('rgba(0,0,0,0.55)', fill === 'none' ? 'none' : 'rgba(0,0,0,0.55)', 3.6, 1.5) : ''}${group(color, fill, 2.2, 0)}</svg>`;
  const id = `${file}-${color.replace(/[^a-z0-9]/gi, '')}-${shadow ? 'shadow' : 'plain'}`;
  for (const scale of [1, 2, 3, 4]) {
    await sharp(Buffer.from(svg), { density: 72 * scale }).png().toFile(path.join(output, `${id}${scale === 1 ? '' : `@${scale}x`}.png`));
  }
  const key = [name, size, color, fill, 2.2, shadow].join('|');
  lines.push(`  ${JSON.stringify(key)}: require('../assets/reel-icons/${id}.png'),`);
}
await fs.writeFile(path.join(root, 'lib/reel-icon-assets.ts'), `// Generated by scripts/generate-reel-icons.mjs from the pinned Lucide package.\n// Lucide ISC license: assets/reel-icons/LICENSE.\nexport const reelIconAssets: Record<string, number> = {\n${lines.join('\n')}\n};\n`);
await fs.copyFile(path.join(root, 'node_modules/lucide-react-native/LICENSE'), path.join(output, 'LICENSE'));
